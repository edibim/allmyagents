// TestCodexConfigureSkipsExistingUntrackedForeignFile proves Finding B at
// the adapter level (not just the shared writeManagedFile helper): a
// pre-existing, untracked, non-AllMyAgents AGENTS.md must survive
// byte-for-byte and Codex must report skipped.
func TestCodexConfigureSkipsExistingUntrackedForeignFile(t *testing.T) {
	projectDir := newGitRepo(t)
	foreignContent := "# My own untracked notes\n\nNot generated by AllMyAgents.\n"
	if err := os.WriteFile(filepath.Join(projectDir, "AGENTS.md"), []byte(foreignContent), 0o644); err != nil {
		t.Fatalf("WriteFile returned error: %v", err)
	}

	result := Codex{}.Configure(projectDir, "- Learning method: Socratic\n")
	if result.Status != StatusSkipped {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusSkipped, result.Detail)
	}

	got := readFile(t, filepath.Join(projectDir, "AGENTS.md"))
	if got != foreignContent {
		t.Fatalf("foreign untracked AGENTS.md was modified:\ngot:  %q\nwant: %q", got, foreignContent)
	}
}
