func TestCodexConfigureWritesAgentsFile(t *testing.T) {
	projectDir := newGitRepo(t)

	result := Codex{}.Configure(projectDir, "- Learning method: Socratic\n")
	if result.Status != StatusConfigured {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusConfigured, result.Detail)
	}

	content := readFile(t, filepath.Join(projectDir, "AGENTS.md"))
	if !strings.Contains(content, "Generated by AllMyAgents") {
		t.Fatalf("expected generated marker in AGENTS.md, got %q", content)
	}
	if !strings.Contains(content, "Learning method: Socratic") {
		t.Fatalf("expected rendered context in AGENTS.md, got %q", content)
	}

	exclude := readFile(t, filepath.Join(projectDir, ".git", "info", "exclude"))
	if !strings.Contains(exclude, "AGENTS.md") {
		t.Fatalf("expected AGENTS.md in git exclude, got %q", exclude)
	}
}

func TestCodexConfigureIsIdempotent(t *testing.T) {
	projectDir := newGitRepo(t)

	if result := (Codex{}.Configure(projectDir, "- A: B\n")); result.Status != StatusConfigured {
		t.Fatalf("first Configure: Status = %q, detail: %s", result.Status, result.Detail)
	}
	first := readFile(t, filepath.Join(projectDir, "AGENTS.md"))

	if result := (Codex{}.Configure(projectDir, "- A: B\n")); result.Status != StatusConfigured {
		t.Fatalf("second Configure: Status = %q, detail: %s", result.Status, result.Detail)
	}
	second := readFile(t, filepath.Join(projectDir, "AGENTS.md"))

	if first != second {
		t.Fatalf("AGENTS.md changed on idempotent call:\nfirst:  %s\nsecond: %s", first, second)
	}
	exclude := readFile(t, filepath.Join(projectDir, ".git", "info", "exclude"))
	if strings.Count(exclude, "AGENTS.md") != 1 {
		t.Fatalf("expected exactly one AGENTS.md exclude entry, got %q", exclude)
	}
}

