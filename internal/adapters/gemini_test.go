// TestGeminiConfigureOutsideGitRepoDoesNotClaimGitExclusion proves Finding
// C: outside a git repository nothing was actually excluded, so the
// success message must not claim it was.
func TestGeminiConfigureOutsideGitRepoDoesNotClaimGitExclusion(t *testing.T) {
	projectDir := t.TempDir()

	result := Gemini{}.Configure(projectDir, "- A: B\n")
	if result.Status != StatusConfigured {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusConfigured, result.Detail)
	}
	if strings.Contains(result.Detail, "git-excluded") {
		t.Fatalf("must not claim git exclusion outside a git repository, got detail %q", result.Detail)
	}
	if !strings.Contains(result.Detail, "no git repository") {
		t.Fatalf("expected an honest 'no git repository' note, got detail %q", result.Detail)
	}
}

// TestGeminiConfigureSkipsExistingUntrackedForeignContentFile proves
// Finding B for Gemini's content file specifically: a pre-existing,
// untracked, non-AllMyAgents GEMINI.local.md must survive byte-for-byte.
func TestGeminiConfigureSkipsExistingUntrackedForeignContentFile(t *testing.T) {
	projectDir := newGitRepo(t)
	foreignContent := "personal Gemini notes, not from AllMyAgents\n"
	if err := os.WriteFile(filepath.Join(projectDir, "GEMINI.local.md"), []byte(foreignContent), 0o644); err != nil {
		t.Fatalf("WriteFile returned error: %v", err)
	}

	result := Gemini{}.Configure(projectDir, "- A: B\n")
	if result.Status != StatusSkipped {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusSkipped, result.Detail)
	}

	got := readFile(t, filepath.Join(projectDir, "GEMINI.local.md"))
	if got != foreignContent {
		t.Fatalf("foreign untracked GEMINI.local.md was modified:\ngot:  %q\nwant: %q", got, foreignContent)
	}
}

