func fileNamesFromSettings(t *testing.T, settings map[string]any) []string {
	t.Helper()
	contextField, ok := settings["context"].(map[string]any)
	if !ok {
		t.Fatalf("expected 'context' object in settings, got %#v", settings)
	}
	raw, ok := contextField["fileName"].([]any)
	if !ok {
		t.Fatalf("expected 'context.fileName' array, got %#v", contextField["fileName"])
	}
	names := make([]string, 0, len(raw))
	for _, v := range raw {
		names = append(names, v.(string))
	}
	return names
}

func containsString(ss []string, want string) bool {
	for _, s := range ss {
		if s == want {
			return true
		}
	}
	return false
}

func writeJSONObjectForTest(t *testing.T, path string, settings map[string]any) {
	t.Helper()
	if err := writeJSONObject(path, settings); err != nil {
		t.Fatalf("writeJSONObject returned error: %v", err)
	}
}
