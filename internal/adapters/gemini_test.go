func TestGeminiConfigureWritesContentFileAndSettings(t *testing.T) {
	projectDir := newGitRepo(t)

	result := Gemini{}.Configure(projectDir, "- Learning method: Socratic\n")
	if result.Status != StatusConfigured {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusConfigured, result.Detail)
	}

	content := readFile(t, filepath.Join(projectDir, "GEMINI.local.md"))
	if !strings.Contains(content, "Generated by AllMyAgents") {
		t.Fatalf("expected generated marker, got %q", content)
	}
	if !strings.Contains(content, "Learning method: Socratic") {
		t.Fatalf("expected rendered context, got %q", content)
	}

	settings := decodeSettings(t, filepath.Join(projectDir, ".gemini", "settings.json"))
	names := fileNamesFromSettings(t, settings)
	if !containsString(names, "GEMINI.local.md") {
		t.Fatalf("expected context.fileName to include GEMINI.local.md, got %v", names)
	}
	if !containsString(names, "GEMINI.md") {
		t.Fatalf("expected context.fileName to still include the default GEMINI.md, got %v", names)
	}

	exclude := readFile(t, filepath.Join(projectDir, ".git", "info", "exclude"))
	if !strings.Contains(exclude, "GEMINI.local.md") || !strings.Contains(exclude, ".gemini/settings.json") {
		t.Fatalf("expected both managed paths in git exclude, got %q", exclude)
	}
}

func TestGeminiConfigurePreservesExistingContextFileNames(t *testing.T) {
	projectDir := newGitRepo(t)
	settingsPath := filepath.Join(projectDir, ".gemini", "settings.json")
	writeJSONObjectForTest(t, settingsPath, map[string]any{
		"context": map[string]any{"fileName": []any{"CONTEXT.md"}},
		"other":   "keep-me",
	})

	result := Gemini{}.Configure(projectDir, "- A: B\n")
	if result.Status != StatusConfigured {
		t.Fatalf("Status = %q, want %q (detail: %s)", result.Status, StatusConfigured, result.Detail)
	}

	settings := decodeSettings(t, settingsPath)
	if settings["other"] != "keep-me" {
		t.Fatalf("expected unrelated settings key to be preserved, got %#v", settings)
	}
	names := fileNamesFromSettings(t, settings)
	if !containsString(names, "CONTEXT.md") || !containsString(names, "GEMINI.local.md") {
		t.Fatalf("expected both the existing and new filenames, got %v", names)
	}
}

func TestGeminiConfigureIsIdempotent(t *testing.T) {
	projectDir := newGitRepo(t)

	if result := (Gemini{}.Configure(projectDir, "- A: B\n")); result.Status != StatusConfigured {
		t.Fatalf("first Configure: Status = %q, detail: %s", result.Status, result.Detail)
	}
	settingsPath := filepath.Join(projectDir, ".gemini", "settings.json")
	firstSettings := readFile(t, settingsPath)

	if result := (Gemini{}.Configure(projectDir, "- A: B\n")); result.Status != StatusConfigured {
		t.Fatalf("second Configure: Status = %q, detail: %s", result.Status, result.Detail)
	}
	secondSettings := readFile(t, settingsPath)

	if firstSettings != secondSettings {
		t.Fatalf("settings.json changed on idempotent call:\nfirst:  %s\nsecond: %s", firstSettings, secondSettings)
	}
}

